def lq(q):
    q = Q(q)
    if q.denominator == 1:
        return f"({q.numerator} : ℝ)"
    return f"(({q.numerator} : ℝ) / {q.denominator})"


def poly_expr(p, var):
    terms = []
    for k, c in enumerate(p):
        if c == 0:
            continue
        mon = "" if k == 0 else (f" * {var}" if k == 1 else f" * {var} ^ {k}")
        terms.append(f"{lq(c)}{mon}")
    return " + ".join(terms) if terms else "0"


def bern(p, n):
    p = p + [Q(0)] * (n + 1 - len(p))
    return [sum(Q(comb(j, i), comb(n, i)) * p[i] for i in range(j + 1)) for j in range(n + 1)]


def bern_expr(beta, var, n, shift):
    """shift + sum_j (beta_j - shift) C(n,j) var^j (1-var)^(n-j)"""
    terms = [lq(shift)]
    for j, bj in enumerate(beta):
        c = (bj - shift) * comb(n, j)
        terms.append(f"{lq(c)} * ({var} ^ {j} * (1 - {var}) ^ {n - j})")
    return " + ".join(terms)


def sub(p, a, b):
    """p(a + (b-a) r) as polynomial in r."""
    r, acc = [], [Q(1)]
    for k, c in enumerate(p):
        if k > 0:
            acc = P.mul(acc, [a, b - a])
        r = P.add(r, P.scale(acc, c))
    return r


